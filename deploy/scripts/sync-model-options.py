"""Generate the agent whitelist from the runtime's typed controls."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'services/runtime/src'))
from media_lab.model_options import CanvasOptions, ImageOptions, VideoOptions, SongOptions, SAMPLERS, SCHEDULERS, option_catalog


def schema(model):
    root = model.model_json_schema()
    definitions = root.get('$defs', {})
    def resolve(value):
        if isinstance(value, list):
            return [resolve(item) for item in value]
        if not isinstance(value, dict):
            return value
        if '$ref' in value:
            return resolve(definitions[value['$ref'].split('/')[-1]])
        if 'anyOf' in value:
            return resolve(next(item for item in value['anyOf'] if item.get('type') != 'null'))
        result = {key: resolve(item) for key, item in value.items() if key not in ('title', 'default', '$defs')}
        if 'properties' in result:
            for name, choices in [('sampler', SAMPLERS), ('scheduler', SCHEDULERS)]:
                if name in result['properties']:
                    result['properties'][name]['enum'] = list(choices)
            result['properties'] = {key: item for key, item in result['properties'].items() if item.get('type') != 'null'}
        return result
    return resolve(root)


content = '/* Generated by deploy/scripts/sync-model-options.py from runtime/model_options.py. */\nmodule.exports = '
content += json.dumps({key: schema(model) for key, model in [('image', CanvasOptions), ('edit', ImageOptions),
                                                            ('video', VideoOptions), ('song', SongOptions)]}, indent=2) + ';\n'
target = ROOT / 'services/agent/lib/model-options.cjs'
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8') == content, 'Model option whitelist is stale'
else:
    target.write_text(content, encoding='utf-8')
if '--qa' in sys.argv:
    (ROOT / 'apps/web/scripts/qa-model-options.json').write_text(json.dumps(option_catalog(), ensure_ascii=False, indent=2), encoding='utf-8')
