"""Keep repository English MCP documentation identical to the shipped server guides."""
import sys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'services/runtime/src'))
from media_lab.mcp_server import GUIDES
from media_lab.mcp_guides import ENGLISH
from media_lab.model_guides import (ACE_STEP, AGENT_BRIEF, DIRECTOR, FLUX3, H3, KANDINSKY6, LANGUAGE, MOSS,
                                    QWEN_EDIT, QWEN_IMAGE, QWEN_TTS, STABLE_AUDIO3, TOPICS, YUE2)

for name, text in [('MCP-GUIDE.md', GUIDES['all']), ('MODEL-CONTROLS.md', '# Model controls\n\n' + GUIDES['controls'])]:
    target = ROOT / 'docs' / name
    if '--check' in sys.argv:
        assert target.read_text(encoding='utf-8') == text, f'{name} is stale; run deploy/scripts/sync-mcp-guides.py'
    else:
        target.write_text(text, encoding='utf-8', newline='\n')

policy = 'Write all model-facing descriptive prompts in English (image/edit/video prompt, music style, Director brief and scene prompts). Faithfully translate descriptive requests while preserving every requirement. Keep lyrics, literal visible text, spoken dialogue, names and ABC notation in their requested original language unless the user asks to translate them. Do not write descriptive model prompts in Spanish. Reply conversationally in the user language and keep the original request unchanged.'
text = '/* Generated by deploy/scripts/sync-mcp-guides.py. */\n'
text += 'const metadata = ' + json.dumps(ENGLISH, ensure_ascii=False, indent=2) + ';\n'
text += 'const modelPromptLanguage = ' + json.dumps(policy) + ';\n'
guides = {'language': LANGUAGE, 'qwenImage': QWEN_IMAGE, 'qwenEdit': QWEN_EDIT, 'moss': MOSS, 'flux3': FLUX3, 'h3': H3,
          'kandinsky6': KANDINSKY6, 'yue2': YUE2, 'aceStep': ACE_STEP, 'stableAudio3': STABLE_AUDIO3, 'qwenTts': QWEN_TTS,
          'director': DIRECTOR, 'agentBrief': AGENT_BRIEF, 'topics': TOPICS}
text += 'const guides = ' + json.dumps(guides, ensure_ascii=False, indent=2) + ';\n'
text += '''function englishCapabilities(value) {
  if (typeof value === 'string') return metadata[value] ?? value;
  if (Array.isArray(value)) return value.map(englishCapabilities);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, englishCapabilities(item)]));
  return value;
}
module.exports = { modelPromptLanguage, englishCapabilities, guides };
'''
target = ROOT / 'services/agent/lib/agent-language.cjs'
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8') == text, 'Agent language policy is stale'
else:
    target.write_text(text, encoding='utf-8', newline='\n')
